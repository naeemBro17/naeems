// Bangladesh administrative geography: Division -> District -> Thana/Upazila,
// bundled at build time so address selection never depends on a runtime API.
//
// Base data (8 divisions, 64 districts, 494 upazilas, English + Bangla names):
// nuhil/bangladesh-geocode (github.com/nuhil/bangladesh-geocode, MIT-style
// public dataset commonly used for this exact purpose).
//
// That dataset's Dhaka and Chattogram districts list only their rural
// upazilas (Savar, Keraniganj, ... / Sitakunda, Patiya, ...) and are missing
// the city police-thana subdivisions most of Naeem's customers actually live
// in. Added on top, as extra thana entries under those two districts:
//   - 50 Dhaka Metropolitan Police thanas (Mirpur, Dhanmondi, Gulshan,
//     Uttara East/West, Mohammadpur, Badda, etc.)
//   - 15 Chattogram Metropolitan Police thanas (Karnaphuli omitted — it
//     duplicates the existing Karnafuli rural upazila)
// Source for both: bn.wikipedia.org's DMP and CMP articles (Thana list
// sections), cross-checked against the matching English Wikipedia articles.
//
// See reports/batch-16.txt for the full list of what was added.

